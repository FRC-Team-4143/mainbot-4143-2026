
package frc.robot.autos;

import edu.wpi.first.math.geometry.Pose2d;
import edu.wpi.first.math.geometry.Rotation2d;
import java.util.Map;
import java.util.OptionalInt;

// If these imports cause errors because you're not using ChoreoLib,
// turn off "Include ChoreoLib-specific Helpers" in Choreo's codegen settings.
import choreo.auto.AutoRoutine;
import choreo.auto.AutoTrajectory;

/**
 * A class containing the name, start pose, end pose, and total time of every Choreo trajectory.
 * This prevents your code from referencing deleted or misspelled trajectories,
 * and removes the need for JSON parsing to load a trajectory's essential data.
 * DO NOT MODIFY THIS FILE YOURSELF! It is automatically generated by Choreo.
 */
public record ChoreoTraj(
    String name,
    OptionalInt segment,
    double totalTimeSecs,
    Pose2d initialPoseBlue,
    Pose2d endPoseBlue
) {
    public static final ChoreoTraj CitrusLeftSide = new ChoreoTraj(
	    "CitrusLeftSide",
	    OptionalInt.empty(),
	    6.42369,
	    new Pose2d(4.416, 7.48, Rotation2d.fromRadians(-1.571)),
	    new Pose2d(2.872, 5.535, Rotation2d.fromRadians(2.503))
	);
	public static final ChoreoTraj CitrusLeftSideSecondPass = new ChoreoTraj(
	    "CitrusLeftSideSecondPass",
	    OptionalInt.empty(),
	    6.79221,
	    new Pose2d(2.887, 5.604, Rotation2d.fromRadians(2.165)),
	    new Pose2d(2.872, 5.535, Rotation2d.fromRadians(1.584))
	);
	public static final ChoreoTraj CitrusRightSide = new ChoreoTraj(
	    "CitrusRightSide",
	    OptionalInt.empty(),
	    5.254,
	    new Pose2d(5.665, 2.412, Rotation2d.fromRadians(0)),
	    new Pose2d(2.755, 2.534, Rotation2d.fromRadians(-2.467))
	);
	public static final ChoreoTraj CitrusRightSideSecondPassNew = new ChoreoTraj(
	    "CitrusRightSideSecondPassNew",
	    OptionalInt.empty(),
	    8.19474,
	    new Pose2d(2.95, 2.475, Rotation2d.fromRadians(-3.123)),
	    new Pose2d(2.95, 2.514, Rotation2d.fromRadians(-2.427))
	);
	public static final ChoreoTraj CitrusSynergyPt1 = new ChoreoTraj(
	    "CitrusSynergyPt1",
	    OptionalInt.empty(),
	    2.35982,
	    new Pose2d(3.495, 5.924, Rotation2d.fromRadians(3.142)),
	    new Pose2d(1.698, 6.725, Rotation2d.fromRadians(-3.13))
	);
	public static final ChoreoTraj CitrusSynergyPt2 = new ChoreoTraj(
	    "CitrusSynergyPt2",
	    OptionalInt.empty(),
	    5.81007,
	    new Pose2d(1.698, 6.725, Rotation2d.fromRadians(-3.13)),
	    new Pose2d(2.651, 3.91, Rotation2d.fromRadians(3.128))
	);
	public static final ChoreoTraj TestPath = new ChoreoTraj(
	    "TestPath",
	    OptionalInt.empty(),
	    4.1157,
	    new Pose2d(2.5, 1, Rotation2d.fromRadians(0)),
	    new Pose2d(2.5, 5, Rotation2d.fromRadians(0))
	);

    /**
     * A map between trajectory names and their corresponding data.
     * This allows for trajectory data to be looked up with strings during runtime.
     */
    public static final Map<String, ChoreoTraj> ALL_TRAJECTORIES = Map.ofEntries(
    	Map.entry("CitrusLeftSide", CitrusLeftSide),
		Map.entry("CitrusLeftSideSecondPass", CitrusLeftSideSecondPass),
		Map.entry("CitrusRightSide", CitrusRightSide),
		Map.entry("CitrusRightSideSecondPassNew", CitrusRightSideSecondPassNew),
		Map.entry("CitrusSynergyPt1", CitrusSynergyPt1),
		Map.entry("CitrusSynergyPt2", CitrusSynergyPt2),
		Map.entry("TestPath", TestPath)
    );

    /**
     * Looks up the ChoreoTraj segment of the given overall ChoreoTraj.
     * WARNING: will raise an exception if not called with a valid segment index.
     */
    public ChoreoTraj segment(int segment) {
        var traj = ChoreoTraj.ALL_TRAJECTORIES.get(this.name + "$" + segment);
        if (traj == null) {
            throw new NullPointerException("Trajectory " + this.name + " does not have segment #" + segment + ".");
        }
        return traj;
    }
    
    // If these methods cause errors because you're not using ChoreoLib,
    // turn off "Include ChoreoLib-specific Helpers" in Choreo's codegen settings.
    /**
     * Load an AutoTrajectory directly from a ChoreoTraj, which may be a segment of a larger trajectory.
     */
    public AutoTrajectory asAutoTraj(AutoRoutine routine) {
        if (this.segment.isPresent()) {
            return routine.trajectory(this.name, this.segment.getAsInt());
        }
        return routine.trajectory(this.name);
    }
}
